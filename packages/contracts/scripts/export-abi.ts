/**
 * Copies the compiled registry's ABI and bytecode into the TypeScript
 * integration package (packages/integrations/src/chain), so the app uses
 * exactly what was compiled and tested here. Run after `hardhat build`:
 *
 *   node --experimental-strip-types scripts/export-abi.ts
 *
 * test/exported-abi.ts fails if the exported files drift from the artifacts.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..");
const target = join(root, "../integrations/src/chain");

export function artifact(name: string, source: string): { abi: unknown[]; bytecode: string } {
  const json = JSON.parse(readFileSync(join(root, "artifacts/contracts", source, `${name}.json`), "utf8"));
  return { abi: json.abi, bytecode: json.bytecode };
}

export function render(constName: string, a: { abi: unknown[]; bytecode: string }, header: string): string {
  return `${header}\nexport const ${constName}_ABI = ${JSON.stringify(a.abi, null, 2)} as const;\n\nexport const ${constName}_BYTECODE = "${a.bytecode}" as const;\n`;
}

export const FILES = [
  {
    path: join(target, "registry-contract.ts"),
    content: () =>
      render(
        "DEAL_REGISTRY",
        artifact("SagolikDealRegistry", "SagolikDealRegistry.sol"),
        "// Generated by packages/contracts/scripts/export-abi.ts from SagolikDealRegistry.sol. Do not edit.\n",
      ),
  },
  {
    path: join(target, "test-usdc-contract.ts"),
    content: () =>
      render("TEST_USDC", artifact("TestUSDC", "test/TestUSDC.sol"), "// Generated by packages/contracts/scripts/export-abi.ts. Test-only token for local integration tests. Do not edit.\n"),
  },
];

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  for (const f of FILES) {
    writeFileSync(f.path, f.content());
    console.log(`wrote ${f.path}`);
  }
}
